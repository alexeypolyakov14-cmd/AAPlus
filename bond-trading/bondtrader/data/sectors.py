"""Отраслевая классификация эмитентов по названию (MOEX не отдаёт сектор для облигаций).

Нужна для лимита концентрации на сектор: в ВДО треть рынка — лизинг и МФО, и дефолты там кластеризуются.
Правила — ключевые слова в полном/кратком названии; переопределение через data/issuers.csv (колонка sector).
"""
from __future__ import annotations

import re

SECTOR_RULES: list[tuple[str, re.Pattern]] = [
    ("gov", re.compile(r"^(ОФЗ|SU\d)|минфин|министерство финансов", re.I)),
    ("subfed", re.compile(r"област|край|республик|округ|москва|санкт-петербург|деп\.? ?финанс|правительств|администрац|муницип", re.I)),
    ("leasing", re.compile(r"лизинг|leasing|лиз\b|-лиз|лизп|балтлиз|интерлиз|роделен|carmoney|рсхбл|гтлк|европлан|ресо-лиз|евролиз", re.I)),
    ("mfo", re.compile(r"мфк|мкк|микрофинанс|микрокредит|займ|займер|быстроденьги|мигкредит|вэббанкир|саммит|лайм|эйрлоанс|carmoney|кармани|мани мен|moneyman|фордевинд|kviku|квику", re.I)),
    ("bank", re.compile(r"банк|bank|кредит[а-я]* организац|нко\b|вэб\.рф|дом\.рф|сбер\b", re.I)),
    ("finance", re.compile(r"финанс|инвест|капитал|factoring|фактор|брокер|страхов|ипотечн|сфо\b|специализированное финансовое|коллект|пко\b|взыскан", re.I)),
    ("real_estate", re.compile(r"девелоп|строй|строит|жилищ|недвиж|пик\b|самолет|эталон|лср|сэтл|брусник|glorax|глоракс|легенда|аквилон|джи-групп|а101|апри", re.I)),
    ("oil_gas", re.compile(r"нефт|газ|роснефт|лукойл|новатэк|газпром|татнефт|сибур|нефтехим", re.I)),
    ("metals", re.compile(r"метал|сталь|нлмк|ммк|северстал|норник|никел|русал|полюс|полиметал|золот|алрос|мечел|тмк|евраз", re.I)),
    ("telecom", re.compile(r"телеком|мтс|ростелеком|мегафон|вымпелком|билайн|связь|эр-телеком", re.I)),
    ("retail", re.compile(r"ритейл|торгов|магнит|x5|икс 5|лента|окей|о'кей|детский мир|м\.видео|мвидео|фикс прайс|азбука|вкусвилл|аптек", re.I)),
    ("agro", re.compile(r"агро|сельхоз|зерн|мясо|молок|птиц|сахар|русагро|черкизово|продимекс|племзавод|ферм", re.I)),
    ("transport", re.compile(r"транспорт|авиа|аэрофлот|ржд|логист|перевоз|порт\b|судох|автодор|такси|каршеринг|делимобил|глобалтрак|монополия", re.I)),
    ("energy", re.compile(r"энерг|электро|россети|гидро|тэк\b|теплосет|интер рао|юнипро|мосэнерго", re.I)),
    ("chemicals", re.compile(r"хим|удобрен|фосагро|акрон|уралкали|куйбышевазот|полипласт", re.I)),
    ("it", re.compile(r"софт|цифров|айти|it\b|технолог|яндекс|вк\b|positive|позитив|селектел|астра|диасофт|м\.тех", re.I)),
    ("industrial", re.compile(r"машин|завод|промышл|оборудован|техник|приборо|авто\b|камаз|соллерс|кировск|уралмаш|станк", re.I)),
    ("consumer", re.compile(r"пищев|напитк|кондитер|мебел|одежд|обув|космет|фарм|медиц|клиник|гемотест", re.I)),
]


def sector_of(name: str, full_name: str = "") -> str:
    text = f"{full_name or ''} {name or ''}".strip()
    for sector, rx in SECTOR_RULES:
        if rx.search(text):
            return sector
    return "other"
